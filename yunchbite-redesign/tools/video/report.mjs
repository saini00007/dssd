// report.md generator.
import { fmtDur } from './util.mjs';

const f = (v, d = 2) => (v == null || !Number.isFinite(v) ? '–' : Number(v).toFixed(d));

export function buildReport({ label, input, probe, crop, timeline, events, profile, noise, strips, sheets, errors, params, args, runtimeSec, params2 }) {
  const L = [];
  const s = probe?.stats;
  L.push(`# Motion analysis: ${label}`, '');
  L.push(`- Input: \`${input}\``, `- Generated by \`tools/video/analyze-video.mjs\`${args ? ` (${args})` : ''}${runtimeSec ? `, runtime ${fmtDur(runtimeSec)}` : ''}`, '');
  if (errors?.length) {
    L.push('## Stage errors', '', 'Stages are failure-isolated; the following failed and their outputs are missing or partial:', '');
    for (const e of errors) L.push(`- **${e.stage}**: ${e.message}`);
    L.push('');
  }
  if (s) {
    L.push('## Recording', '',
      `| Property | Value |`, `|---|---|`,
      `| Resolution | ${probe.width}×${probe.height} (${probe.codec}) |`,
      `| Duration | ${f(s.duration, 3)} s |`,
      `| Frames | ${s.frames} |`,
      `| Nominal fps (r_frame_rate) | ${f(s.nominalFps, 2)} |`,
      `| Container avg fps | ${f(s.avgFpsContainer, 2)} |`,
      `| Measured avg fps (frames/duration) | ${f(s.avgFps, 2)} |`,
      `| Median frame interval | ${f(s.medianDt * 1000, 1)} ms (${f(s.medianFps, 2)} fps) |`,
      `| Min / p95 / max frame interval | ${f(s.minDt * 1000, 1)} / ${f(s.p95Dt * 1000, 1)} / ${f(s.maxDt * 1000, 1)} ms |`,
      `| Frames preceded by a gap > 1.5× median (recorder drops) | ${s.gapFrames} (${f((100 * s.gapFrames) / s.frames, 1)}%) |`, '',
      `The recording is **variable frame rate**: every number below uses each frame's real timestamp, never an assumed fps.`, '');
  }
  if (crop) {
    L.push('## Crop (browser chrome removed)', '',
      `- Content rectangle in source pixels: **${crop.w}×${crop.h} at x=${crop.x}, y=${crop.y}** (\`--crop ${crop.w}:${crop.h}:${crop.x}:${crop.y}\`), source: ${crop.source}`,
      `- Right edge excluded: ${probe ? probe.width - (crop.x + crop.w) : '?'} px, bottom: ${probe ? probe.height - (crop.y + crop.h) : '?'} px, top: ${crop.y} px, left: ${crop.x} px`,
      `- Preview: [crop-preview.jpg](crop-preview.jpg) (red box = analysed area)`, '');
  }
  if (timeline?.length) {
    const cnt = {}; for (const fr of timeline) cnt[fr.class] = (cnt[fr.class] || 0) + 1;
    L.push('## Frame classes', '', '| class | frames | share |', '|---|---|---|');
    for (const k of ['idle', 'scroll', 'animate', 'scroll+animate', 'cut']) L.push(`| ${k} | ${cnt[k] || 0} | ${f((100 * (cnt[k] || 0)) / timeline.length, 1)}% |`);
    const low = timeline.filter((x) => x.lowConf).length;
    L.push('', `Noise floor (idle residual, 30th percentile, min 0.3): **${f(noise?.floorIdle, 2)}** gray levels. Low-confidence frames (changing but textureless, scroll not measurable): ${low}.`, '');
  }
  if (profile) {
    L.push('## Scroll profile', '',
      `- Vertical scroll bursts: **${profile.bursts}**; total path ${profile.totalDownPx} px down, ${profile.totalUpPx} px up (source px, cumulative, resets at cuts)`,
      `- Peak velocity ${profile.peakVelocity} px/s; median burst peak ${profile.medianPeakVelocity} px/s; median burst mean ${profile.medianMeanVelocity} px/s`,
      profile.medianDecayTau != null
        ? `- **Smooth-scroll decay:** exponential tail fitted on ${profile.decayFits}/${profile.bursts} bursts (R² ≥ 0.8): median time constant **τ ≈ ${f(profile.medianDecayTau, 3)} s** (velocity falls to 1/e every τ; a Lenis-style lerp). Per-burst values below.`
        : `- No clean exponential decay tail found (needs ≥5 tail samples with R² ≥ 0.8).`, '');
    const bursts = events.filter((e) => e.type === 'scroll');
    if (bursts.length) {
      L.push('| ID | time | duration | dir | distance px | peak px/s | mean px/s | decay τ (R²) |', '|---|---|---|---|---|---|---|---|');
      for (const b of bursts) L.push(`| ${b.id} | ${f(b.startT)}–${f(b.endT)} s | ${Math.round(b.duration * 1000)} ms | ${b.direction} | ${f(Math.abs(b.distancePx), 0)} | ${f(b.peakVelocity, 0)} | ${f(b.meanVelocity, 0)} | ${b.decay?.tau ? `${f(b.decay.tau, 3)} s (${f(b.decay.r2, 2)})` : '–'} |`);
      L.push('');
    }
  }
  if (events?.length) {
    const by = {}; for (const e of events) by[e.type] = (by[e.type] || 0) + 1;
    L.push('## Events', '', `Counts: ${Object.entries(by).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '',
      '| ID | type | start–end | frames | duration | region | peak energy | strip |', '|---|---|---|---|---|---|---|---|');
    for (const e of events) {
      const st = strips?.[e.id];
      const link = st && !st.error ? `[strip](${st.strip.replace(/ /g, '%20')})${st.of > st.shown ? ` (${st.shown}/${st.of})` : ''}` : st?.error ? 'error' : '';
      L.push(`| ${e.id} | ${e.type} | ${f(e.startT, 3)}–${f(e.endT, 3)} s | f#${e.startFrame}–${e.endFrame} (${e.frames}) | ${Math.round(e.duration * 1000)} ms | ${e.region || ''} | ${f(e.peakEnergy, 1)} | ${link} |`);
    }
    L.push('');
    const cuts = events.filter((e) => e.type === 'cut');
    if (cuts.length) {
      L.push('### Cuts', '');
      for (const c of cuts) L.push(`- **${c.id}** at ${f(c.startT, 3)}–${f(c.endT, 3)} s (f#${c.startFrame}–${c.endFrame}): ${c.note}. ffmpeg scene score peak ${f(c.sceneScorePeak, 2)}.`);
      L.push('');
    }
    const pinned = events.filter((e) => e.type === 'pinned');
    if (pinned.length) {
      L.push('### Likely pinned / scroll-scrubbed sections', '');
      for (const p of pinned) L.push(`- **${p.id}** ${f(p.startT, 2)}–${f(p.endT, 2)} s (${Math.round(p.duration * 1000)} ms, ${p.region}): ${p.mergedAnimations} animation bursts merged; page did not move vertically yet kept changing, with scrolling immediately before and after. This is a heuristic: confirm by stepping the strip.`);
      L.push('');
    }
  }
  if (sheets?.files?.length) L.push('## Contact sheets', '', `${sheets.frames} frames in ${sheets.files.length} sheets under \`sheets/\` (overview only, picked by nearest real timestamp):`, '', sheets.files.map((x) => `- [${x}](${x.replace(/ /g, '%20')})`).join('\n'), '');
  L.push('## Outputs', '',
    '- `timeline.json` per-frame: n, t, dt, dy, dx (source px since previous frame; dy>0 = scrolled down), confidence, scrollVelocity (px/s, centred 3-frame), scrollPos, residual, rawDiff, regionGrid (4×3 residual), class',
    '- `events.json` events with start/end frame + time, region, peak energy, scroll stats', '- `timeline.png` whole-recording chart', '- `sheets/` overview contact sheets', '- `events/E##-<type>/strip.jpg` frame-by-frame filmstrips (+ `frames/`)', '- `viewer.html` frame stepper (open from this folder; video loaded by relative path)', '');
  L.push('## Method notes', '',
    '- Decode once, gray, cropped, scaled to ~360 px wide; per consecutive pair: vertical shift by SAD (coarse at half scale over ±45% height, refine ±3 px, parabola sub-pixel), then horizontal shift (±30% width) at that dy. Robust (clamped) SAD so fixed UI and flying objects do not dominate.',
    '- Confidence = SAD contrast of the best minimum against the median and against the second-best minimum. A shift is only accepted when it clearly beats zero shift AND confidence ≥ 0.25; otherwise dy = 0 (so textureless dark frames are low-confidence, never fake scroll).',
    '- Residual = mean |frame − shifted previous frame| over the overlap (bilinear sub-pixel); energy = residual above the idle noise floor (or above a speed-dependent floor while scrolling, because parallax and sub-pixel resampling add residual). Region = 4×3 grid of residual.',
    '- Cut = very poor alignment (high clamped SAD after best shift AND almost no gain over zero shift), cross-checked with ffmpeg `scene`; cut frames closer than 1 s are merged into one navigation event.',
    '- Pinned = long in-place change with no vertical shift and scroll bursts within 1.5 s on both sides (not directly after a cut).', '');
  L.push('## Limitations (read before trusting a number)', '',
    '- **VFR / dropped frames:** the recorder emits frames irregularly (gaps up to ' + (s ? Math.round(s.maxDt * 1000) : '?') + ' ms here). Timing is only as good as the frame timestamps; animations shorter than the gaps are under-sampled. Per-frame velocities near duplicated/dropped frames are noisy, hence the 3-frame smoothing and 2-frame peak windows.',
    '- **Recorded at the display/recorder rate, not the site\'s render rate:** at ~25-30 fps a 60 fps CSS/GSAP easing is sampled coarsely. For easing curves, record at 60 fps if the recorder allows.',
    '- **4 fps contact sheets vs full strips:** sheets skip ~85% of frames; use event strips (every frame, or the stated stride when long) for timing/easing studies.',
    '- **Cursor and hover:** the mouse cursor is ~0.03% of pixels and is not filtered; fast cursor motion alone should not trigger events, but cursor-driven hover effects do (by design).',
    '- **Textureless frames** (dark empty backgrounds, fades): scroll cannot be measured; they are low-confidence and treated as not scrolling. A scroll across a uniform area is invisible to any image-based method.',
    '- **Scroll shifts are global:** one dy/dx per frame. Parallax layers, sticky headers and pinned content move differently from the dominant layer; they show up as residual energy, not as extra scroll.',
    '- **Smooth-scroll decay** is fitted on the displacement derivative of 3-frame windows; wheel notches that overlap in time (multi-impulse bursts) are fitted after the last strong impulse and can be biased.',
    '- **Pinned/scroll-scrubbed detection is heuristic:** the wheel/scrollbar is not visible, so "kept changing while the user was scrolling" is inferred from adjacent scroll bursts. The scrollbar thumb (excluded by the crop) would be a stronger signal.',
    '- **Compression noise:** H.264 keyframe refreshes cause brief residual spikes; the ≥3-frame rule and the noise floor suppress most but not all.', '');
  return L.join('\n');
}
