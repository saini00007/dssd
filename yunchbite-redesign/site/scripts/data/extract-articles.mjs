// Parses the harvested article pages and writes src/data/articles.ts.
// Run: node scripts/data/extract-articles.mjs   (from site/)
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const PAGES = resolve(here, "../../../research/current-site/pages");
const OUT = resolve(here, "../../src/data/articles.ts");

const MONTHS = { January: "01", February: "02", March: "03", April: "04", May: "05", June: "06", July: "07", August: "08", September: "09", October: "10", November: "11", December: "12" };

// slug, category, hero name, hero alt, product block placement (after the Nth body block, 1-based)
const ARTICLES = [
  { slug: "why-makhana-is-the-perfect-smart-snack", category: "Health & Wellness", hero: "blog-makhana", alt: "A bowl of seasoned, crunchy makhana with scattered fox nuts", product: "makhana-zipper-peri-peri", after: "end" },
  { slug: "the-power-of-nuts-small-bite-big-benefits", category: "Health & Wellness", hero: "blog-nuts", alt: "Almonds and cashews ready to snack on", product: "dryfruits-roasted-almonds", after: "end" },
  { slug: "popcorn-the-crunchy-snack-you-can-feel-good-about", category: "Snacking Tips", hero: "blog-popcorn", alt: "A bowl of fluffy golden popcorn", product: "popcorn-salted", after: "end" },
  { slug: "discover-our-range-of-healthy-snacks", category: "Our Products", hero: "blog-products", alt: "The Yunch Bite range of makhana, popcorn and dry fruits", product: "makhana-zipper-salt-pepper", after: 1 },
  { slug: "healthy-snacking-habits-for-the-whole-family", category: "Lifestyle", hero: "blog-family", alt: "A family snacking together at home", product: "makhana-pillow-chatpataa", after: 1 },
];

const clean = (s) =>
  s.replace(/Yunch\s?[Bb]ite/g, "Yunch Bite").replace(/Peri-\s+Peri/g, "Peri-Peri").replace(/Chatpataa/g, "Chatpata").replace(/\s+/g, " ").trim();

const out = ARTICLES.map((a) => {
  const dir = `${PAGES}/articles-${a.slug}`;
  const md = readFileSync(`${dir}/content.md`, "utf8");
  const meta = JSON.parse(readFileSync(`${dir}/meta.json`, "utf8"));
  const lines = md.slice(md.indexOf("\n# ")).split("\n").map((l) => l.trim()).filter(Boolean);
  const title = lines[0].replace(/^# /, "");
  // lines[1] avatar image, [2] author, [3] role, [4] date, [5] read time, [6] hero image, [7] lead quote
  const author = clean(lines[2]);
  const role = clean(lines[3]);
  const dm = lines[4].match(/^(\d+) (\w+) (\d{4})$/);
  const date = `${dm[3]}-${MONTHS[dm[2]]}-${dm[1].padStart(2, "0")}`;
  const readTime = lines[5];
  const lead = clean(lines[7].replace(/^[“"]|[”"]$/g, ""));
  const end = lines.findIndex((l) => l.startsWith("[Back to Blogs"));
  const raw = lines.slice(8, end);
  const body = [];
  let list = null;
  for (const l of raw) {
    const ol = l.match(/^\d+\.\s+(.*)$/);
    if (ol) { (list ??= { type: "ol", items: [] }).items.push(clean(ol[1])); continue; }
    if (list) { body.push(list); list = null; }
    if (l.startsWith("## ")) body.push({ type: "h2", text: clean(l.slice(3)) });
    else body.push({ type: "p", text: clean(l) });
  }
  if (list) body.push(list);
  const prod = { type: "product", slug: a.product };
  if (a.after === "end") body.push(prod);
  else body.splice(a.after + 1, 0, prod); // after the first h2 + paragraph
  return {
    slug: a.slug, title: clean(title), category: a.category, date, readTime,
    author: { name: author, role }, hero: `/photos/blog/${a.slug}.webp`, heroAlt: a.alt,
    lead, body, metaTitle: clean(meta.title), metaDescription: clean(meta.description),
  };
});

writeFileSync(
  OUT,
  `// GENERATED by scripts/data/extract-articles.mjs from the harvest, then free to edit by hand.
// Text is exactly as on the current site; only spelling/brand-name formatting was cleaned.
// Health claims in these articles are flagged for legal review in docs/current-content-inventory.md.
import type { Article } from "./types";

export const articles: Article[] = ${JSON.stringify(out, null, 2)};

export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

/** Newest first. */
export function articlesByDate(): Article[] {
  return [...articles].sort((a, b) => b.date.localeCompare(a.date));
}

export function moreArticles(current: Article, n = 3): Article[] {
  return articlesByDate().filter((a) => a.slug !== current.slug).slice(0, n);
}
`,
);
console.log("wrote", out.length, "articles");
